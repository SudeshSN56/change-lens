"""Turns tile 02353's after-image into the faint ASCII "lens" used behind the open and end card.

Run from the repo root with the venv:  .venv/Scripts/python.exe video/make_ascii.py
Writes video/src/ascii.js (an exported array of strings).
"""
import json
from pathlib import Path

import cv2
import numpy as np

COLS, ROWS = 64, 30  # mono cells are ~0.6 wide x 1.2 tall, so 64x30 reads as a circle
RAMP = " .,-^+*1o"  # light -> dark, the character set the reference uses

root = Path(__file__).resolve().parent
img = cv2.imread(str(root.parent / "data/second/im2/02353.png"), cv2.IMREAD_GRAYSCALE)
small = cv2.resize(img, (COLS, ROWS), interpolation=cv2.INTER_AREA).astype(np.float32) / 255
small = cv2.equalizeHist((small * 255).astype(np.uint8)).astype(np.float32) / 255

yy, xx = np.mgrid[0:ROWS, 0:COLS]
r = np.hypot((xx - COLS / 2 + 0.5) / (COLS / 2), (yy - ROWS / 2 + 0.5) / (ROWS / 2))
dark = (1 - small) * np.clip((1 - r) / 0.25, 0, 1)  # fade to blank at the lens edge

lines = ["".join(RAMP[int(v * (len(RAMP) - 1) + 0.5)] for v in row).rstrip() for row in dark]
assert len(lines) == ROWS and max(map(len, lines)) <= COLS
(root / "src/ascii.js").write_text(
    "// Generated by make_ascii.py from data/second/im2/02353.png. Do not edit by hand.\n"
    f"export const ASCII = {json.dumps(lines, indent=0)};\n",
    encoding="utf-8",
)
print("\n".join(lines))
